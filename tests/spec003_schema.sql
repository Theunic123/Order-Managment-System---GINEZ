-- Esquema aislado para SPEC-003. Solo contiene estructura y datos sintéticos.
CREATE ROLE web_anon NOLOGIN;
GRANT web_anon TO postgres;

CREATE TABLE public.ubicaciones (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL UNIQUE,
    tipo text NOT NULL CHECK (tipo IN ('SUCURSAL', 'CEDIS'))
);

CREATE TABLE public.cargas_etl (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_reporte text,
    nombre_archivo text,
    hash_archivo bytea CHECK (hash_archivo IS NULL OR octet_length(hash_archivo) = 32),
    ubicacion_id smallint REFERENCES public.ubicaciones(id),
    fecha_desde date,
    fecha_hasta date,
    fecha_carga timestamptz DEFAULT now(),
    usuario_referencia text,
    filas_leidas integer,
    filas_validas integer,
    filas_rechazadas integer,
    estatus text,
    detalle_error text
);
CREATE INDEX cargas_etl_hash_archivo_idx ON public.cargas_etl (hash_archivo);

CREATE TABLE public.ventas_historicas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sucursal text,
    fecha date,
    documento text,
    folio text,
    cliente text,
    sku text,
    desc_sicar text,
    cantidad numeric,
    importe numeric,
    total numeric,
    ubicacion_id smallint REFERENCES public.ubicaciones(id),
    carga_id integer REFERENCES public.cargas_etl(id)
);
CREATE UNIQUE INDEX ventas_v1_identidad_uidx
    ON public.ventas_historicas (ubicacion_id, fecha, folio, sku)
    WHERE ubicacion_id IS NOT NULL AND fecha IS NOT NULL
      AND folio IS NOT NULL AND sku IS NOT NULL;

CREATE TABLE public.cargas_etl_rechazos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carga_id integer REFERENCES public.cargas_etl(id),
    fila_origen integer,
    motivos text[],
    datos_originales jsonb,
    fecha_registro timestamptz DEFAULT now()
);

